"""Generate independent app/server icon artifacts from the authoritative catalog.

This offline generator uses only Python's standard library. Artwork preparation
is a separate, explicitly documented operation; checking never downloads assets.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = Path("packages/app_icon_catalog")
APPS = (Path("."), Path("desktop_companion"), Path("apps/bluetooth"))
SERVER_ASSETS = Path("community_server/assets/app_icons")
IDENTIFIER = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def checked_relative(value):
    path = Path(value)
    if path.is_absolute() or value.startswith("/") or ".." in path.parts or "\\" in value or ":" in value:
        raise ValueError("Catalog paths must be contained relative paths")
    return path


def png_size(data):
    if not 45 <= len(data) <= 65536 or data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("Invalid or oversized PNG")
    offset, pixels, dimensions = 8, bytearray(), None
    ended = False
    while offset < len(data):
        size = struct.unpack(">I", data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        chunk = data[offset + 8:offset + 8 + size]
        crc = data[offset + 8 + size:offset + 12 + size]
        if len(crc) != 4 or struct.unpack(">I", crc)[0] != zlib.crc32(kind + chunk):
            raise ValueError("PNG chunk CRC mismatch")
        if kind == b"IHDR":
            width, height, depth, color, compression, filtering, interlace = struct.unpack(">IIBBBBB", chunk)
            if (width, height, depth, color, compression, filtering, interlace) != (256, 256, 8, 6, 0, 0, 0):
                raise ValueError("Expected a non-interlaced 256px RGBA PNG")
            dimensions = (width, height)
        elif kind == b"IDAT":
            pixels.extend(chunk)
        elif kind == b"IEND":
            ended = True
        offset += size + 12
    if not dimensions or not ended or offset != len(data):
        raise ValueError("Incomplete PNG")
    expected_size = 256 * (256 * 4 + 1)
    inflater = zlib.decompressobj()
    decoded = inflater.decompress(pixels, expected_size + 1)
    if len(decoded) != expected_size or not inflater.eof or inflater.unconsumed_tail or inflater.unused_data:
        raise ValueError("Invalid PNG pixel data")
    return dimensions


def load_catalog(root):
    package = root / PACKAGE
    data = json.loads((package / "catalog.json").read_text(encoding="utf-8"))
    icons = data["icons"]
    if (data["schemaVersion"] != 1 or data["builtinCount"] != 50
            or not isinstance(data["webOnlyCount"], int) or data["webOnlyCount"] < 10
            or len(icons) != 50 + data["webOnlyCount"]
            or sum(icon["bundled"] for icon in icons) != 50):
        raise ValueError("Expected fifty built-ins and at least ten registered web-only icons")
    names, hashes = set(), set()
    for icon in icons:
        if not IDENTIFIER.fullmatch(icon["id"]) or not icon["name"].strip():
            raise ValueError("Invalid icon identity")
        for identity in [icon["id"], *icon["aliases"]]:
            key = identity.casefold()
            if not IDENTIFIER.fullmatch(identity) or key in names or key == "codex":
                raise ValueError("Duplicate or invalid product ID/alias")
            names.add(key)
        asset = package / checked_relative(icon["png"])
        source = package / checked_relative(icon["original"])
        if asset.is_symlink() or source.is_symlink():
            raise ValueError("Artwork sources cannot be links")
        raw = asset.read_bytes()
        if png_size(raw) != (icon["width"], icon["height"]) or len(raw) != icon["bytes"]:
            raise ValueError("Artwork dimensions/size mismatch")
        digest = hashlib.sha256(raw).hexdigest()
        if digest != icon["sha256"] or digest in hashes:
            raise ValueError("Artwork hash mismatch or duplicate image")
        hashes.add(digest)
        if hashlib.sha256(source.read_bytes()).hexdigest() != icon["originalSha256"]:
            raise ValueError("Original source hash mismatch")
        if not icon["termsUrl"].startswith("https://") or not icon["sourcePageUrl"].startswith("https://"):
            raise ValueError("Source and terms pages require HTTPS")
        if not icon["sourceUrl"].startswith(("https://", "native-resource:")):
            raise ValueError("Invalid source location")
    if data["legacyAliases"] != {"codex": "chatgpt"}:
        raise ValueError("Unexpected legacy protocol alias")
    return data


def literal(value):
    # JSON string literals are valid Dart/Rust strings here; no interpolation.
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def dart_catalog(icons):
    text = """// GENERATED by scripts/generate_app_icon_catalog.py. Do not edit.
// dart format off
// Self-contained data: safe to vendor with the independent Bluetooth edition.
class BuiltinIconEntry {
  const BuiltinIconEntry({required this.id, required this.name,
    required this.aliases, required this.assetPath, required this.sha256,
    required this.version, required this.sourceUrl, required this.sourcePageUrl,
    required this.termsUrl, required this.width, required this.height});
  final String id, name, assetPath, sha256, version, sourceUrl, sourcePageUrl, termsUrl;
  final List<String> aliases;
  final int width, height;
}

const builtinIconCatalog = <BuiltinIconEntry>[
"""
    for icon in icons:
        args = {key: icon[key] for key in ("id", "name", "sha256", "version", "sourceUrl", "sourcePageUrl", "termsUrl", "width", "height")}
        args["assetPath"] = "assets/app_icons/" + icon["id"] + ".png"
        fields = ",\n    ".join(f"{key}: {literal(value) if isinstance(value, str) else value}" for key, value in args.items())
        aliases = ", ".join(literal(alias) for alias in icon["aliases"])
        text += f"  BuiltinIconEntry(\n    {fields},\n    aliases: [{aliases}],\n  ),\n"
    return text + """ ];

BuiltinIconEntry? builtinIconById(String id) {
  final normalized = id.trim().toLowerCase();
  for (final icon in builtinIconCatalog) {
    if (icon.id.toLowerCase() == normalized ||
        icon.aliases.any((alias) => alias.toLowerCase() == normalized)) {
      return icon;
    }
  }
  return null;
}

String? canonicalBuiltinIconId(String id) => builtinIconById(id)?.id;

/// Historical wire/config compatibility only. Never used as a product alias.
String legacyProtocolIconId(String id) =>
    id.trim().toLowerCase() == 'codex' ? 'chatgpt' : id;
"""


def server_records(data):
    return [{"app_id": icon["id"], "canonical_id": icon["id"], "name": icon["name"],
             "aliases": icon["aliases"], "download_url": "/v1/icons/" + icon["id"],
             "mime_type": "image/png", "source": icon["sourceUrl"],
             "source_page_url": icon["sourcePageUrl"], "terms_url": icon["termsUrl"],
             "license": icon["rightsStatus"], "available": True, "bundled": icon["bundled"],
             "sha256": icon["sha256"], "version": icon["version"],
             "width": icon["width"], "height": icon["height"]} for icon in data["icons"]]


def rust_catalog(data):
    lines = ["// GENERATED by scripts/generate_app_icon_catalog.py. Do not edit.", f'const CATALOG_VERSION: &str = {json.dumps(data["version"])};', "#[rustfmt::skip]", "const ICONS: &[IconRecord] = &["]
    for icon in server_records(data):
        lines.append("    IconRecord {")
        for key, value in icon.items():
            if isinstance(value, list):
                rendered = "&[" + ", ".join(json.dumps(alias) for alias in value) + "]"
            else:
                rendered = json.dumps(value, ensure_ascii=False)
            lines.append(f"        {key}: {rendered},")
        lines.append("    },")
    lines += ["];", "", "#[rustfmt::skip]", "fn png_asset(id: &str) -> Option<&'static [u8]> {", "    Some(match id {"]
    for icon in data["icons"]:
        lines.append(f'        "{icon["id"]}" => include_bytes!("../assets/app_icons/{icon["id"]}.png"),')
    return "\n".join(lines + ["        _ => return None,", "    })", "}", ""])


def expected_files(root, data, include_lite=True):
    files = {}
    builtins = [icon for icon in data["icons"] if icon["bundled"]]
    dart = dart_catalog(builtins).encode("utf-8")
    for app in APPS if include_lite else APPS[:2]:
        files[app / "lib/icons/builtin_icon_catalog.g.dart"] = dart
        for icon in builtins:
            files[app / "assets/app_icons" / (icon["id"] + ".png")] = (root / PACKAGE / icon["png"]).read_bytes()
    for icon in data["icons"]:
        files[SERVER_ASSETS / (icon["id"] + ".png")] = (root / PACKAGE / icon["png"]).read_bytes()
    files[Path("community_server/src/builtin_icon_catalog.g.rs")] = rust_catalog(data).encode("utf-8")
    server = {"schema_version": 1, "version": data["version"], "brand_count": len(data["icons"]),
              "built_in_count": 50, "web_only_count": data["webOnlyCount"],
              "legacy_aliases": data["legacyAliases"], "icons": server_records(data)}
    files[SERVER_ASSETS / "catalog.json"] = (json.dumps(server, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    files[SERVER_ASSETS / "registered_sources.json"] = files[SERVER_ASSETS / "catalog.json"]
    return files


def generate(root=ROOT, check=False, include_lite=True):
    data = load_catalog(root)
    expected = expected_files(root, data, include_lite=include_lite)
    differences = []
    for relative, content in expected.items():
        target = root / relative
        if target.is_symlink():
            raise ValueError("Generated output cannot be a link")
        if not target.exists() or target.read_bytes() != content:
            differences.append(str(relative))
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
    # These icon directories are managed resources. Only stale PNG files are
    # removed; unrelated source vectors/documentation are never traversed.
    apps = APPS if include_lite else APPS[:2]
    for directory in [*(app / "assets/app_icons" for app in apps), SERVER_ASSETS]:
        for stale in (root / directory).glob("*.png"):
            if stale.relative_to(root) not in expected:
                differences.append(str(stale.relative_to(root)))
                if not check:
                    if stale.is_symlink():
                        raise ValueError("Stale generated icon is a link")
                    stale.unlink()
    if check and differences:
        raise ValueError("Generated icon artifacts differ: " + ", ".join(differences))
    return len(data["icons"])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--full-only", action="store_true", help="For isolated Full source exports: do not generate or require Bluetooth Lite")
    options = parser.parse_args()
    count = generate(check=options.check, include_lite=not options.full_only)
    print(f"Validated {count} unique icons (50 bundled / {count - 50} online).")
